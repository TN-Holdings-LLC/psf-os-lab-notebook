"""The loop's records of 2026-11-18 and 2026-11-19 judged again with a between-job term (receiver for the loopvar test's
DRIFTS; workplace Claude, 2026-11-20; not declared, no device). psf-os after-2026-11-20: loop.rejudge and
next_stacks(between_job_sigma=...).

For each night and each sigma (the excess between-job standard deviation of g; loopvar's s_b gives it tonight), round
by round: the verdicts with SE = sqrt(g_se^2 + sigma^2), the rule from the rounds so far, and the first round whose
rule differs from the recorded one. Beyond that round the records say nothing (the night would have run other
stacks), so the table stops there. Per HELPS row, sigma* = sqrt((g / 2)^2 - g_se^2): the sigma at which it turns
NOT SHOWN.

  python notes/receivers_2026-11-20/rejudge_loop.py [--sigmas 0,0.005,...]       (psf-os after-2026-11-20 on the path)
"""
import argparse
import json
import math
import os

from psf_os import loop as LP

NB = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
NIGHTS = {   # night -> (records, rungs of that night's rule): 11-18 ran os2's rule (no rungs), 11-19 the rungs M, F
    "2026-11-18": ("results/os2-night-2026-11-18", ()),
    "2026-11-19": ("results/loop-night-2026-11-19", ("M", "F")),
}
KEYS = ("stacks", "stop")


def rounds_of(d):
    out, k = [], 1
    while os.path.exists(os.path.join(d, f"r{k}", "round_scores.json")):
        out.append(json.load(open(os.path.join(d, f"r{k}", "round_scores.json"))))
        k += 1
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sigmas", default="0,0.004,0.005,0.0075,0.01,0.0125,0.015,0.02,0.025,0.03")
    a = ap.parse_args()
    sigmas = [float(x) for x in a.sigmas.split(",")]
    lines = []
    say = lambda s: (print(s), lines.append(s))
    for night, (rel, rungs) in NIGHTS.items():
        d = os.path.join(NB, rel)
        rs = rounds_of(d)
        say(f"## {night} ({rel}; rungs {list(rungs) or 'none (os2)'}; {len(rs)} rounds)")
        say("")
        for r in rs:
            for key, row in r["rows"].items():
                if row.get("verdict") == "PRESCRIPTION HELPS":
                    s_star = math.sqrt(max((row["g"] / 2) ** 2 - row["g_se"] ** 2, 0.0))
                    say(f"- r{r['round']} L{key} {'+'.join(row['stack'])}: g {row['g']:+.4f}, shot SE {row['g_se']:.4f}"
                        f" -> HELPS up to sigma* = {s_star:.4f}")
        say("")
        say("| sigma | verdicts per round (L1 L2 L3; H helps, N not shown, O overshoot, - none) | first rule that "
            "differs from the record | what it would have been |")
        say("|---|---|---|---|")
        for s in sigmas:
            vs, first, what = [], "none (every recorded rule again)", ""
            for k in range(1, len(rs) + 1):
                jr = LP.rejudge(rs[k - 1], s)
                vs.append(f"r{k} " + " ".join({"PRESCRIPTION HELPS": "H", "NOT SHOWN": "N", "OVERSHOOT": "O"}.get(
                    jr["rows"][key]["verdict"], "-") for key in sorted(jr["rows"])))
                rec = os.path.join(d, f"RULE{k + 1}.json")
                if not os.path.exists(rec):
                    break
                R = LP.next_stacks(rs[:k], rungs, q_choice=lambda *x: None, between_job_sigma=s)
                Rr = json.load(open(rec))
                if any(R[x] != Rr[x] for x in KEYS):
                    first = f"RULE{k + 1}"
                    ch = [f"L{key} {'+'.join(Rr['stacks'][key])} -> {'+'.join(R['stacks'][key])} ({R['why'][key]})"
                          for key in R["stacks"] if R["stacks"][key] != Rr["stacks"][key]]
                    if R["stop"] != Rr["stop"]:
                        ch.append(f"stop {Rr['stop']} -> {R['stop']} (" + (R["stop_reason"] or "the night goes on: an L "
                                  "NOT SHOWN for the first time, its stack kept for one more round") + ")")
                    what = "; ".join(ch)
                    break
            say(f"| {s:.4f} | {'; '.join(vs)} | {first} | {what} |")
        say("")
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "rejudge_loop.md"), "w").write(
        "# The loop's records judged again with a between-job term (generated by rejudge_loop.py)\n\n"
        + "\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
